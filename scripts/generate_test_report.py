"""
生成测试用财报PDF
"""

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
import os

def create_test_financial_report():
    """创建测试财报PDF"""

    # 创建PDF
    pdf_path = "测试财报_贵州茅台2023年报.pdf"
    c = canvas.Canvas(pdf_path, pagesize=A4)
    width, height = A4

    # 添加标题
    c.setFont("Helvetica-Bold", 24)
    c.drawString(100, height - 100, "Guizhou Moutai Co., Ltd.")

    c.setFont("Helvetica", 18)
    c.drawString(100, height - 130, "2023 Annual Financial Report")

    # 财务数据
    c.setFont("Helvetica-Bold", 14)
    c.drawString(100, height - 200, "Key Financial Indicators")

    c.setFont("Helvetica", 12)
    y_position = height - 230

    financial_data = [
        ("Revenue (RMB)", "150,000,000,000"),
        ("Net Profit (RMB)", "75,000,000,000"),
        ("Total Assets (RMB)", "500,000,000,000"),
        ("Total Liabilities (RMB)", "150,000,000,000"),
        ("Current Assets (RMB)", "300,000,000,000"),
        ("Current Liabilities (RMB)", "80,000,000,000"),
        ("Accounts Receivable (RMB)", "8,000,000,000"),
        ("Inventory (RMB)", "60,000,000,000"),
        ("Operating Cash Flow (RMB)", "90,000,000,000"),
    ]

    for label, value in financial_data:
        c.drawString(120, y_position, f"{label}:")
        c.drawString(350, y_position, value)
        y_position -= 25

    # 财务比率
    c.setFont("Helvetica-Bold", 14)
    c.drawString(100, y_position - 30, "Financial Ratios")

    c.setFont("Helvetica", 12)
    y_position -= 60

    ratios = [
        ("Debt Ratio", "30.0%"),
        ("Current Ratio", "3.75"),
        ("Receivable/Revenue Ratio", "5.3%"),
        ("Inventory Turnover", "2.5"),
        ("Cash Flow Quality", "1.2"),
    ]

    for label, value in ratios:
        c.drawString(120, y_position, f"{label}:")
        c.drawString(350, y_position, value)
        y_position -= 25

    # 页脚
    c.setFont("Helvetica", 10)
    c.drawString(100, 50, "This is a test financial report for demonstration purposes only.")
    c.drawString(100, 35, "Generated by TURAQ Financial Analysis System")

    c.save()

    return pdf_path

if __name__ == "__main__":
    pdf_path = create_test_financial_report()
    print(f"测试财报已生成: {pdf_path}")
